#[test]
fn noop_on_macos() {
    use std::os::unix::process::ExitStatusExt;
    use std::sync::Mutex;
    use zapbrew_prefix::{CommandOutput, CommandRunner, CommandSpec};

    struct SwVersRunner {
        records: Mutex<usize>,
    }
    impl CommandRunner for SwVersRunner {
        fn run(&self, _spec: &CommandSpec) -> Result<CommandOutput, std::io::Error> {
            *self.records.lock().expect("records") += 1;
            Ok(CommandOutput::new(
                std::process::ExitStatus::from_raw(0),
                b"15.0\n".to_vec(),
                Vec::new(),
            ))
        }
    }
    let runner = SwVersRunner {
        records: Mutex::new(0),
    };

    let (_temp, root) = utf8_temp();
    let prefix = root.join("prefix");
    plant_brewed_gcc(&prefix);
    plant_brewed_glibc(&prefix);
    let input = EnvDetectInput {
        os: "macos".to_owned(),
        arch: "arm64".to_owned(),
        home: prefix.to_path_buf(),
        xdg_cache_home: None,
        vars: HashMap::from([
            ("HOMEBREW_PREFIX".to_owned(), prefix.to_string()),
            (
                "HOMEBREW_CELLAR".to_owned(),
                prefix.join("Cellar").to_string(),
            ),
            ("HOMEBREW_TEMP".to_owned(), prefix.join("tmp").to_string()),
        ]),
        available_parallelism: 2,
    };
    let env = match Env::detect_from(&input, &runner) {
        Ok(env) => env,
        Err(err) => panic!("detect env: {err}"),
    };
    match setup_preferred_gcc_libs(&env) {
        Ok(()) => {}
        Err(err) => panic!("macOS setup: {err}"),
    }
    assert!(
        !conf_path(&prefix).exists(),
        "macOS must not write a Linux ld.so.conf snippet"
    );
}

#[test]
fn does_not_panic_or_error_on_empty_prefix() {
    let (_temp, root) = utf8_temp();
    let prefix = root.join("prefix");
    let env = linux_env(&prefix);
    // No gcc, no glibc — must be a clean no-op, not an error.
    match setup_preferred_gcc_libs(&env) {
        Ok(()) => {}
        Err(PrefixError::NoSystemLdSo) => return,
        Err(err) => panic!("empty prefix setup: {err}"),
    }
    assert!(!conf_path(&prefix).exists());
}
